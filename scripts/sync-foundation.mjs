import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Shared source is maintained once; installed skills carry standalone copies.
const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
for (const file of ['foundation.md', 'lexicon.md']) {
const body = readFileSync(new URL(`shared/${file}`, root), 'utf8');
const content = `<!-- Generated by scripts/sync-foundation.mjs from shared/${file}. Do not edit this copy. -->\n\n` + body;
for (const skill of ['orient', 'clarify', 'deconstruct', 'explain']) {
  const dir = new URL(`skills/${skill}/references/`, root);
  const target = new URL(file, dir);
  if (check) {
    let actual;
    try { actual = readFileSync(target, 'utf8'); } catch { actual = null; }
    if (actual !== content) {
      console.error(`Shared reference out of sync: ${fileURLToPath(target)}`);
      process.exitCode = 1;
    }
  } else {
    mkdirSync(dir, { recursive: true });
    writeFileSync(target, content);
  }
}
}
